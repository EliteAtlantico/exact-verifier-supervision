"""analysis_report.py -- compose results/analysis/README.md from stats.json, probe.json, rules.json, tokens.json.

usage (full refresh, CPU only; the tokenizer step runs in its own process):
    python experiments/analysis_stats.py
    python experiments/analysis_probe.py          # ~3 min per task; --tasks t1,t2 refreshes only those
    python experiments/analysis_rules.py
    python experiments/analysis_tokens.py
    python experiments/analysis_report.py
Every number in the README comes from those JSON files, so re-running after new runs land keeps it in sync.
"""
from __future__ import annotations

import json
import os

import analysis_common as C

C.fix_sys_path()

MAIN_N = 180
M15 = C.DEFAULT_MODEL
# the "trivial rule" baselines named in the analysis plan (fixed rules, nothing fitted)
TRIVIAL = {"majority", "odd", "last_digit_1379", "no_factor_le_3", "no_factor_le_5", "no_factor_le_7",
           "last_digit_is_7", "last_digit_is_3", "last_digit_is_1", "last_digit_0_or_5", "last_digit_even",
           "digit_sum_div_7", "digit_sum_div_3", "digit_sum_div_11", "digit_sum_div_13", "digit_sum_div_2",
           "contains_digit_7"}


def load(name):
    p = os.path.join(C.OUT, name)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def pct(x, d=1):
    return "-" if x is None else f"{100 * x:.{d}f}"


def main():
    st, pr, ru, tk = load("stats.json"), load("probe.json"), load("rules.json"), load("tokens.json")
    KEY = []
    L = ["# Analysis of the thinking-vs-data runs (auto-generated by experiments/analysis_report.py)", "",
         "Qwen2.5 LoRA runs graded by the exact gate; 240 test items per task (120 Yes / 120 No). "
         "All numbers come from stats.json, probe.json, rules.json and tokens.json in this directory; "
         "the full tables are in stats.md, probe.md and rules.md. Re-run order: see experiments/analysis_report.py.", ""]
    pooled = {(r["task"], r["model"], r["arm"], r["n"]): r for r in st["pooled"]} if st else {}
    boots = {(b["comparison"], b["task"], b["model"], b["n"]): b for b in st["bootstrap"]} if st else {}
    tests = st["mcnemar"] if st else []
    rules_by = {}
    for x in (ru or {}).get("runs", []):
        rules_by.setdefault((x["task"], x["arm"], x["n"], C.short_model(x["model"])), []).append(x)

    # ---------------------------------------------------------------- 1. headline table
    L += [f"## 1. Main cell: n = {MAIN_N}, {C.short_model(M15)}", "",
          "A = answer-only, B = trace then answer, C = scrambled trace. Accuracy pooled over seeds [Wilson 95%]; "
          "B-A = paired bootstrap over items and seeds [95% CI]; p = exact McNemar per seed (Holm across tasks "
          "within comparison and seed). Best probe = the probe chosen by 5-fold CV on the same 180 training items "
          "(mean test accuracy over draws for seeds 0-2); best rule = best fixed trivial rule on the test set.", "",
          "| task | base | A | B | C | B-A pp [95% CI] | McNemar B vs A per seed | best probe | best trivial rule | A's closest shortcut rule |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    tasks = sorted({k[0] for k in pooled if k[1] == M15 and k[3] in (MAIN_N, 0)},
                   key=lambda t: (t not in ("prime", "valid", "div7"), t))
    for t in tasks:
        cells = {}
        for arm in ("A", "B", "C"):
            r = pooled.get((t, M15, arm, MAIN_N))
            cells[arm] = (f"{pct(r['acc'])} [{pct(r['wilson95'][0], 0)}, {pct(r['wilson95'][1], 0)}] "
                          f"(s{','.join(map(str, r['seeds']))})") if r else "-"
        base = pooled.get((C.cell_label(t.split("->")[-1], t.split("->")[-1], "base"), M15, "base", 0))
        if not any(cells[a] != "-" for a in cells):
            continue
        b = boots.get(("B-A", t, M15, MAIN_N))
        ba = f"{100 * b['diff']:+.1f} [{100 * b['ci95'][0]:+.1f}, {100 * b['ci95'][1]:+.1f}]" if b else "-"
        mc = "; ".join(f"s{x['seed']}: {100 * x['diff']:+.1f}, p={x['p_exact']:.1g} (Holm {x['p_holm_tasks']:.1g})"
                       for x in tests if x["comparison"] == "B-A" and x["task"] == t and x["model"] == M15
                       and x["n"] == MAIN_N) or "-"
        pt = (pr or {}).get("tasks", {}).get(t.split("->")[-1])
        if pt:
            bp = pt["summary"]["best_probe_cv_mean"]
            names = sorted({v["best_probe_cv"]["probe"] for v in pt["per_seed"].values()})
            probe = f"{pct(bp)} ({'/'.join(names)}; max on test {pct(pt['summary']['best_probe_test_mean'])})"
            rs = {k: v for k, v in pt["rules_summary"].items() if k in TRIVIAL}
            br = max(rs, key=rs.get) if rs else None
            rule = f"{pct(rs[br])} ({br})" if br else "-"
        else:
            probe = rule = "-"
            br = None
        sh = []
        for x in rules_by.get((t, "A", MAIN_N, C.short_model(M15)), []):
            if "best_shortcut_rule" in x:
                sh.append(f"s{x['seed']}: {x['best_shortcut_rule']} {pct(x['best_shortcut_agreement'])}% "
                          f"(kappa {x['best_shortcut_kappa']:.2f} vs truth {x['true_label_kappa']:.2f})")
        ar = pooled.get((t, M15, "A", MAIN_N))
        if ar:
            kline = f"- **{t}**: A {pct(ar['acc'])}%"
            if pt:
                kline += (f" vs best CV-selected surface probe {pct(pt['summary']['best_probe_cv_mean'])}% "
                          f"(A - probe {100 * (ar['acc'] - pt['summary']['best_probe_cv_mean']):+.1f} pp)")
            if br:
                kline += f"; best trivial rule {br} {pct(rs[br])}%"
            if b:
                kline += f"; B - A {ba} pp over seeds {','.join(map(str, b['seeds']))}"
            KEY.append(kline + ".")
        L.append(f"| {t} | {pct(base['acc']) if base else '-'} | {cells['A']} | {cells['B']} | {cells['C']} | {ba} | "
                 f"{mc} | {probe} | {rule} | {'; '.join(sh) or '-'} |")

    other = [b for b in (st or {}).get("bootstrap", []) if b["model"] != M15 and b["comparison"] in ("B-A", "B-C")]
    if other:
        L += ["", "### Other models", "", "| model | task | n | comparison | seeds | diff pp [95% CI] | A | B |",
              "|---|---|---|---|---|---|---|---|"]
        for b in sorted(other, key=lambda b: (b["model"], b["task"], b["comparison"])):
            a_, b_ = pooled.get((b["task"], b["model"], "A", b["n"])), pooled.get((b["task"], b["model"], "B", b["n"]))
            L.append(f"| {C.short_model(b['model'])} | {b['task']} | {b['n']} | {b['comparison']} | "
                     f"{','.join(map(str, b['seeds']))} | {100 * b['diff']:+.1f} [{100 * b['ci95'][0]:+.1f}, "
                     f"{100 * b['ci95'][1]:+.1f}] | {pct(a_['acc']) if a_ else '-'} | {pct(b_['acc']) if b_ else '-'} |")

    # ---------------------------------------------------------------- 2. A vs probe
    if pr:
        L += ["", "## 2. Is answer-only fine-tuning (A) about what a surface probe gets from the same 180 examples?", "",
              "| task | A (pooled) | logreg one-hot | logreg + engineered | MLP one-hot / eng. | kNN one-hot / eng. | "
              "best probe (CV) | full-pool logreg eng. |", "|---|---|---|---|---|---|---|---|"]
        for t, r in pr["tasks"].items():
            a = pooled.get((C.cell_label(r["train_task"], t, "A"), M15, "A", MAIN_N))
            s = r["summary"]
            fp = r.get("full_pool_reference", {}).get("logreg_b", {}).get("test_acc")
            L.append(f"| {t} | {pct(a['acc']) if a else '-'} | {pct(s['logreg_a'])} | {pct(s['logreg_b'])} | "
                     f"{pct(s['mlp_a'])} / {pct(s['mlp_b'])} | {pct(s['knn_a'])} / {pct(s['knn_b'])} | "
                     f"{pct(s['best_probe_cv_mean'])} | {pct(fp)} |")
        L += ["", "Engineered number features = last digit even / in {0,5}, digit sum mod 3 and mod 9, alternating "
              "sum mod 11 (one-hot). For valid, 'one-hot' = bag of word tokens and 'engineered' adds character "
              "1-3-grams and atom-abstracted word n-grams (letters renamed v1, v2, ... by first appearance)."]
        tr = pr["tasks"].get("prime", {}).get("rules_summary")
        if tr:
            L += ["", "Trivial prime rules on the 240-item test set: " + ", ".join(
                f"{k} {pct(tr[k])}" for k in ("odd", "last_digit_1379", "no_factor_le_3", "no_factor_le_5",
                                              "no_factor_le_7") if k in tr) + "."]

    # ---------------------------------------------------------------- 3. prime shortcut detail
    if ru:
        L += ["", "## 3. Which rule does A follow on prime?", "",
              "| arm | n | seed | acc | agree odd | agree last digit in {1,3,7,9} | agree no factor<=3 | <=5 | <=7 | truth | "
              "even comp. acc | odd comp. w/ factor<=7: P(pred prime) | hard comp. (no factor<=7): P(pred prime) | primes acc |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for x in ru["runs"]:
            if x["task"] != "prime" or x["arm"] not in ("A", "A_tok", "B") or C.short_model(x["model"]) != C.short_model(M15):
                continue
            g, s = x["agreement"], x["strata"]
            L.append(f"| {x['arm']} | {x['n']} | {x['seed']} | {pct(x['acc'])} | {pct(g['odd'])} | {pct(g['last_digit_1379'])} | "
                     f"{pct(g['no_factor_le_3'])} | {pct(g['no_factor_le_5'])} | {pct(g['no_factor_le_7'])} | {pct(g['true_label'])} | "
                     f"{pct(s['even_composite']['acc'], 0)} | {s['odd_composite_factor_le7']['p_pred_yes']:.2f} | "
                     f"{s['hard_composite_no_factor_le7']['p_pred_yes']:.2f} | {pct(s['prime']['acc'], 0)} |")
        a_pr = [x for x in ru["runs"] if x["task"] == "prime" and x["arm"] == "A" and x["n"] == MAIN_N
                and C.short_model(x["model"]) == C.short_model(M15)]
        if a_pr:
            KEY.append("- **prime shortcut**: A@180 agrees with 'last digit in {1,3,7,9}' on "
                       + ", ".join(f"{pct(x['agreement']['last_digit_1379'])}% (s{x['seed']})" for x in a_pr)
                       + " of test items vs " + ", ".join(f"{pct(x['agreement']['true_label'])}%" for x in a_pr)
                       + " with the truth; best-kappa shortcut: "
                       + ", ".join(f"{x.get('best_shortcut_rule')} (kappa {x.get('best_shortcut_kappa', 0):.2f})" for x in a_pr) + ".")
        if ru.get("S6"):
            L += ["", "S6 (PREDICTIONS.md) on hard negatives (odd composites with no factor <= 7): "
                  + "; ".join(f"{x['task']} n={x['n']} s{x['seed']} ({x['n_hard']} items, {x['pred_source'].split('_')[0]}): "
                              f"agree rule {pct(x['agree_rule_no_factor_le7'])}% vs truth {pct(x['agree_true_label'])}%"
                              for x in ru["S6"]) + ". On the original 240-item set this subset is small; prime_hard "
                  "(all 240 items odd with no factor <= 7) is the preregistered test."]

    # ---------------------------------------------------------------- 4. prereg + tokens
    if st:
        L += ["", "## 4. Preregistered decision rules (auto-evaluated where the runs exist)", ""]
        L += [f"- **{k}: {v['status']}** " + ("-- " + "; ".join(v["detail"]) if v["detail"] else "") for k, v in st["prereg"].items()]
    if tk:
        dc = tk["digit_check"]
        L += ["", "## 5. Tokenizer and training tokens (real Qwen2.5 tokenizer)", "",
              f"- Digits: {dc['verdict']} ({dc['exhaustive_4digit_contexts_checked']} contexts checked: bare, "
              "'Is n a prime number?', 'Is n divisible by 7?'); 6-digit examples also split into single digits.",
              "- Loss-bearing tokens per 180-example draw (completion + EOS, one epoch; x3 for the 3 epochs), mean over seeds 0-2:", "",
              "| task | " + " | ".join(["A", "B", "C", "Bprime"]) + " | B / A | B tokens per whitespace token |", "|---|---|---|---|---|---|---|"]
        for t, d in tk["train_tokens"].items():
            arms = d["arms"]
            row = [f"{arms[a]['mean_completion_tokens']:.0f}" if a in arms else "-" for a in ("A", "B", "C", "Bprime")]
            b = arms.get("B")
            L.append(f"| {t} | " + " | ".join(row) + f" | {b['ratio_vs_A']:.1f} | "
                     f"{b['seeds']['0']['tokens_per_ws_token']:.2f} |" if b else f"| {t} | " + " | ".join(row) + " | - | - |")
        ok = [v["ws_matches_recorded_run"] for d in tk["train_tokens"].values() for a in d["arms"].values()
              for v in a["seeds"].values() if v["ws_matches_recorded_run"] is not None]
        L += ["", f"- Sampling replica check: the whitespace-token count of the replicated draw equals the train_tokens "
              f"recorded by the worker in {sum(ok)}/{len(ok)} recorded (task, arm, seed) cells; A, B and C of one seed "
              "train on the same 180 items (pools share item order). C's per-draw length differs slightly from B's "
              "because C's traces are permuted across the whole pool (length-matched corpus-wide, not per draw)."]
    if KEY:
        at = L.index(f"## 1. Main cell: n = {MAIN_N}, {C.short_model(M15)}")
        L[at:at] = ["## Key numbers", ""] + KEY + [""]
    L += ["", "## Caveats", "",
          "- Per-item predictions are recovered from correctness bitmaps (wrong = flipped label); an unparseable "
          "answer ('?') counts as a flip. Where results/v2/gens exist, rules.json uses the observed predictions instead.",
          "- 'max on test' probe numbers are selected on the test set (optimistic); the CV-selected probe is the honest one.",
          "- The engineered number features include digit sum mod 3 (= n mod 3) and alternating sum mod 11 (= n mod 11), "
          "so on div3/div11 the 'engineered' probes are handed the answer; the one-hot probes are the fair surface "
          "baseline there. On prime they supply partial-sieve features (n mod 2, 3, 5, 11), which is why they beat A.",
          "- On prime_hard every item is odd with no factor <= 7, so 'last digit in {1,3,7,9}', 'odd' and 'no factor <= 7' "
          "all predict Yes on every item: any of them gives 50% there.",
          "- The pooled Wilson interval treats items x seeds as independent; the paired bootstrap respects item pairing "
          "and seed variation, and is wide when only 2 seeds exist (e.g. valid B: 100% and 80%).", ""]
    open(os.path.join(C.OUT, "README.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"report -> {os.path.relpath(os.path.join(C.OUT, 'README.md'), C.ROOT)}")


if __name__ == "__main__":
    main()
